// Builds Handspell's ISL examples from the landmark files made by isl-extract.py:
//   src/sign/isl/examples.js   built-in example handshapes for the matcher, and each letter's
//                               usual range for the measurements its hints talk about
// (The reference drawings come from tools/isl-poses.py.)
//
//   node tools/isl-build.mjs
//
// Reads tools/data/isl/: realsign-train.jsonl (RealSign, CC0), mendeley.jsonl (multimodal ISL,
// CC BY 4.0) and ayesha.jsonl (ISL image dataset by Ayesha Hannure and others, Apache 2.0).
// Only numbers derived from the landmarks are written; no images.
import { readFileSync, writeFileSync } from 'node:fs';
import { measurePair, PAIR_KEYS } from '../src/sign/isl/features.js';
import { ISL_LETTERS, ISL_ALPHABET } from '../src/sign/isl/letters.js';

const here = (p) => new URL(p, import.meta.url);
const load = (f) => readFileSync(here(f), 'utf8').trim().split('\n').map((l) => JSON.parse(l));
const asHands = (r) => r.hands.map((h) => ({ lm: h.lm.map(([x, y, z]) => ({ x, y, z })), label: h.label, score: h.score }));
const feat = (r) => measurePair(asHands(r), { aspect: r.w / r.h });

const COLLECTIONS = ['realsign-train', 'mendeley', 'ayesha'];
const PER_LETTER = 60; // examples per letter from each collection: a few signers' habits shouldn't swamp the rest
// The tracker often loses one hand of a two-hand letter. Those frames are kept, but at most
// ONE_HAND_SHARE of a two-hand letter's examples, so that a lone hand doesn't look like that letter.
const ONE_HAND_SHARE = 0.6;

const items = [];
const counts = {};
for (const name of COLLECTIONS) {
  const rows = load(`./data/isl/${name}.jsonl`);
  counts[name] = rows.length;
  const byL = {};
  for (const r of rows) { const f = r.hands.length ? feat(r) : null; if (f) (byL[r.letter] ||= []).push({ r, f }); }
  for (const [l, list] of Object.entries(byL)) {
    let pool = list;
    if (ISL_LETTERS[l].hands === 2) {
      const two = list.filter((x) => x.f.nHands === 2), one = list.filter((x) => x.f.nHands === 1);
      pool = [...two, ...one.slice(0, Math.floor((two.length * ONE_HAND_SHARE) / (1 - ONE_HAND_SHARE)))];
    }
    const step = Math.max(1, pool.length / PER_LETTER);
    for (let i = 0; i < pool.length; i += step) items.push(pool[Math.floor(i)]);
  }
}

// Scale of each measurement: half its 10-90% spread over all examples
const q = (vals, p) => vals[Math.min(vals.length - 1, Math.max(0, Math.floor(vals.length * p)))];
const scale = {};
for (const k of PAIR_KEYS) {
  const vals = items.map((x) => x.f[k]).filter(Number.isFinite).sort((a, b) => a - b);
  scale[k] = vals.length ? Math.max(1e-3, (q(vals, 0.9) - q(vals, 0.1)) / 2) : 1;
}
// Stored as (value - offset) / step in a signed byte: offset is the median, step a tenth of the scale
const offset = {};
for (const k of PAIR_KEYS) {
  const vals = items.map((x) => x.f[k]).filter(Number.isFinite).sort((a, b) => a - b);
  offset[k] = vals.length ? vals[Math.floor(vals.length / 2)] : 0;
}
const step = Object.fromEntries(PAIR_KEYS.map((k) => [k, Math.max(scale[k] / 10, 0.05)]));
// Each example: its letter's index, then every measurement as a whole multiple of step[key],
// clipped to a signed byte (-128 means "not measured"), all packed into one base64 string
const rowLen = PAIR_KEYS.length + 1;
const bytes = new Int8Array(items.length * rowLen);
items.forEach(({ r, f }, n) => {
  bytes[n * rowLen] = ISL_ALPHABET.indexOf(r.letter);
  PAIR_KEYS.forEach((k, i) => {
    bytes[n * rowLen + 1 + i] = Number.isFinite(f[k]) ? Math.max(-127, Math.min(127, Math.round((f[k] - offset[k]) / step[k]))) : -128;
  });
});
const packed = Buffer.from(bytes.buffer).toString('base64');

// Usual ranges (10-90%) for the measurements the hints use, per letter, from examples showing
// the letter's number of hands
const ranges = {};
for (const l of ISL_ALPHABET) {
  const def = ISL_LETTERS[l];
  const mine = items.filter((x) => x.r.letter === l && x.f.nHands === def.hands);
  ranges[l] = {};
  for (const [k] of def.hints) {
    const vals = mine.map((x) => x.f[k]).filter(Number.isFinite).sort((a, b) => a - b);
    if (vals.length >= 8) ranges[l][k] = [+q(vals, 0.1).toFixed(3), +q(vals, 0.9).toFixed(3)];
  }
}

const round = (o) => JSON.stringify(o, (k, v) => (typeof v === 'number' ? +v.toFixed(4) : v));
writeFileSync(here('../src/sign/isl/examples.js'), `// Generated by tools/isl-build.mjs. Do not edit by hand.
// Built-in ISL example handshapes, as measurements (see features.js), from three openly licensed
// photo collections: RealSign (CC0), the multimodal ISL dataset by Hambir, Khandagale,
// Cherian, Gaikwad and colleagues (CC BY 4.0), and the ISL image dataset by Ayesha Hannure
// and others (Apache License 2.0). ${items.length} examples of ${PAIR_KEYS.length} measurements, in examples (base64): per example, a
// byte for the letter, then a signed byte per measurement: (value - offset[key]) / step[key]
// (-128: not measured). ranges: each letter's usual range for the measurements its hints use.
export const ISL_DATA = {
  letters: ${JSON.stringify(ISL_ALPHABET.join(''))},
  keys: ${JSON.stringify(PAIR_KEYS)},
  scale: ${round(scale)},
  offset: ${round(offset)},
  step: ${round(step)},
  ranges: ${round(ranges)},
  examples: '${packed}',
};
`);
console.log(`examples: ${items.length}`, counts);
