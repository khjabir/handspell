// Fits each condition's range to the landmark data: the 10th to 90th percentile of the letter's
// samples, with every source weighted equally. Training data: ASL Alphabet (K), ASL Alphabet
// Test (T) and the Surrey signers, minus any signers held out with HOLDOUT.
//
//   node tools/tune.mjs                 fit on everything and write src/sign/tuned.js
//   HOLDOUT=T,D,E node tools/tune.mjs   leave signers out (then run evaluate.mjs to test on them)
//
// Signers: K = ASL Alphabet, T = ASL Alphabet Test, A-E = the five Surrey signers.
import { readFileSync, writeFileSync } from 'node:fs';
import { toPoints, measure } from '../src/sign/features.js';
import { LETTERS } from '../src/sign/letters.js';
const here = (p) => new URL(p, import.meta.url);

const QLO = Number(process.env.QLO || 0.1), QHI = 1 - QLO;
const rows = JSON.parse(readFileSync(here('./data/samples.json'), 'utf8'));
const src = (s) => (s === 'K' ? 'K' : s === 'T' ? 'T' : 'S');
const HELD_OUT = new Set((process.env.HOLDOUT || '').split(',').filter(Boolean));
const byLetter = {};
for (const r of rows) {
  const [label, signer, method, hand, ...v] = r;
  if (HELD_OUT.has(signer)) continue;
  const lm = []; for (let k = 0; k < 21; k++) lm.push([v[k * 3], v[k * 3 + 1], v[k * 3 + 2]]);
  const f = measure(toPoints(lm, { mirror: hand === 'Right' }));
  f.src = src(signer);
  (byLetter[label] ||= []).push(f);
}
const angular = (name) => /(Curl|Mcp|Pip|Dip|Tilt|Dir|spread|Hook)/.test(name);
function wquantile(items, key, q) {
  // items: [{v, w}] sorted by v
  const tot = items.reduce((a, b) => a + b.w, 0);
  let acc = 0;
  for (const it of items) { acc += it.w; if (acc / tot >= q) return it.v; }
  return items[items.length - 1].v;
}
// One softness unit per measurement: a quarter of its 10-90% spread over all letters.
const SOFT = Number(process.env.SOFT || 0.6);
const unit = {};
{
  const all = Object.values(byLetter).flat();
  for (const k of Object.keys(all[0])) {
    if (typeof all[0][k] !== 'number') continue;
    const vals = all.map((f) => f[k]).filter(Number.isFinite).sort((a, b) => a - b);
    unit[k] = (vals[Math.floor(vals.length * 0.9)] - vals[Math.floor(vals.length * 0.1)]) / 4;
  }
}
const out = {};
for (const [letter, def] of Object.entries(LETTERS)) {
  const samples = byLetter[letter] || [];
  def.variants.forEach((variant, vi) => {
    let pool = variant.pick ? samples.filter(variant.pick) : samples;
    let counts = {}; for (const f of pool) counts[f.src] = (counts[f.src] || 0) + 1;
    // A source with only a handful of samples here would get too much weight: leave it out.
    pool = pool.filter((f) => counts[f.src] >= 20);
    counts = {}; for (const f of pool) counts[f.src] = (counts[f.src] || 0) + 1;
    if (pool.length < 30) { console.log('skip', letter, vi, pool.length); return; }
    out[`${letter}.${vi}`] = variant.spec.map((c) => {
      const items = pool.map((f) => ({ v: f[c.f], w: 1 / counts[f.src] })).filter((x) => Number.isFinite(x.v)).sort((a, b) => a.v - b.v);
      const lo = wquantile(items, c.f, QLO), hi = wquantile(items, c.f, QHI);
      const r = (x) => +x.toFixed(angular(c.f) ? 1 : 3);
      return [r(lo), r(hi), r(Math.max(1e-3, SOFT * unit[c.f]))];
    });
    console.log(letter, vi, variant.name || '', pool.length, JSON.stringify(counts));
  });
}
const body = Object.entries(out).map(([k, v]) => `  '${k}': ${JSON.stringify(v)},`).join('\n');
writeFileSync(here('../src/sign/tuned.js'), `// Generated by the tuning script from public ASL alphabet landmark data (see the README).
// Ranges for the conditions in letters.js, in the same order: [low, high, softness].
export const TUNED = {
${body}
};
`);
