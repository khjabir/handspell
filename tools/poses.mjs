// Builds src/hand3d/poses.js: the median handshape for each letter, in the hand's own frame,
// from the landmark data, plus a viewing angle that makes each letter read clearly.
//
//   node tools/poses.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { toPoints, measure } from '../src/sign/features.js';
const here = (p) => new URL(p, import.meta.url);
const rows = JSON.parse(readFileSync(here('./data/samples.json'), 'utf8'));
// Which collections to take each letter from: the clearest examples of the textbook form
const SRC = { default: ['K', 'T'], T: ['A', 'B', 'C', 'D', 'E'] };
// How to turn the hand for each letter (degrees; see src/hand3d/render.js). Others face the
// viewer with a slight turn.
const ORIENT = {
 "C": {
  "roll": 0,
  "yaw": 70
 },
 "O": {
  "roll": 0,
  "yaw": 70
 },
 "G": {
  "roll": 90,
  "pitch": 180,
  "yaw": 25
 },
 "H": {
  "roll": 90,
  "pitch": 180,
  "yaw": 25
 },
 "P": {
  "roll": 150,
  "pitch": -30,
  "yaw": 40
 },
 "Q": {
  "roll": 200,
  "yaw": -60
 },
 "X": {
  "roll": 0,
  "yaw": 45
 },
 "Z": {
  "roll": 0
 },
 "J": {
  "roll": 0
 }
};
const byLetter = {};
for (const r of rows) {
  const [label, signer, , hand, ...v] = r;
  if (label.length !== 1 || !(SRC[label] || SRC.default).includes(signer)) continue;
  const lm = []; for (let k = 0; k < 21; k++) lm.push([v[k * 3], v[k * 3 + 1], v[k * 3 + 2]]);
  const f = measure(toPoints(lm, { mirror: hand === 'Right' }));
  if (label === 'T' && f.thumbGap < -0.8) continue; // the textbook T: thumb between index and middle
  (byLetter[label] ||= []).push({ L: f.L, handDir: f.handDir });
}
const median = (a) => { const s = [...a].sort((x, y) => x - y); return s[Math.floor(s.length / 2)]; };
const lines = Object.keys(byLetter).sort().map((l) => {
  const list = byLetter[l];
  const pts = [];
  for (let i = 0; i < 21; i++) pts.push([0, 1, 2].map((k) => +median(list.map((x) => x.L[i][k])).toFixed(3)));
  const roll = median(list.map((x) => x.handDir));
  const o = ORIENT[l] || {};
  const view = { roll: o.roll ?? +Math.max(-15, Math.min(15, roll)).toFixed(1), yaw: o.yaw ?? -14, pitch: o.pitch ?? 0 };
  return `  ${l}: { view: ${JSON.stringify(view)}, pts: ${JSON.stringify(pts)} },`;
});
writeFileSync(here('../src/hand3d/poses.js'), `// Reference handshape for each letter: 21 points in the hand's own frame (x towards the thumb
// side, y up the hand, z out of the palm; palm lengths), taken as the median of hundreds of
// MediaPipe landmark sets per letter from public ASL alphabet photos (see the README). \`view\`
// turns the hand so the letter reads clearly (degrees: roll, yaw, pitch; see render.js).
// Generated by tools/poses.mjs.
export const POSES = {
${lines.join('\n')}
};
`);
console.log('wrote src/hand3d/poses.js');
